# ---- grid helpers: a glyph is a list of equal-length strings, one per font row ----

def to_grid(g):
    return [''.join('#' if r >> (g['w'] - 1 - x) & 1 else '.' for x in range(g['w'])) for r in g['rows']]


def to_glyph(grid):
    return {'w': len(grid[0]), 'rows': [int(r.replace('#', '1').replace('.', '0'), 2) for r in grid]}


def art(h, top, rows):
    """Rows drawn starting at font row `top`, padded with blank rows to height h."""
    w = len(rows[0])
    assert all(len(r) == w for r in rows), rows
    return ['.' * w] * top + list(rows) + ['.' * w] * (h - top - len(rows))


def mirror(grid):
    """Mirrors the ink horizontally, keeping the glyph's left/right bearings."""
    ink = [x for x in range(len(grid[0])) if any(r[x] == '#' for r in grid)]
    a, b = ink[0], ink[-1] + 1
    return [r[:a] + r[a:b][::-1] + r[b:] for r in grid]


def over(grid, top, rows, dx=0):
    """Ors `rows` onto grid starting at row `top`, column dx."""
    g = [list(r) for r in grid]
    for i, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == '#':
                g[top + i][dx + x] = '#'
    return [''.join(r) for r in g]


def hcat(*grids):
    return [''.join(p) for p in zip(*grids)]


def widen(grid, n):
    return [r + '.' * n for r in grid]


def small(grid, keep, top, base):
    """Small-caps form: capital rows `keep` restacked to end on the baseline row `base`;
    rows below the baseline (descenders) are kept as they are."""
    w = len(grid[0])
    body = [grid[k] for k in keep]
    return ['.' * w] * (base + 1 - len(body)) + body + grid[base + 1:]


