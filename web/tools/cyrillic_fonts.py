"""Adds Cyrillic (U+0410-044F, Ё ё) and typographic punctuation (№ « » — – …) to the converted
bitmap fonts in assets/fonts, and renders 3x specimen PNGs next to them.

Glyphs are drawn as ASCII art ('#' = pixel) in the style of each font. Letters with a Latin twin copy
the Latin glyph; the rest reuse Latin parts (mirrors, row subsets = small caps, overlays) or are drawn
by hand. Existing glyphs are never modified: a code point already occupied by an original glyph
(« » in rmn6_13 / rmn4_08 hold game-specific graphics) is skipped.

Idempotent: our code points are recomputed from the Latin glyphs on every run.
Run after tools/extract.py (which regenerates the fonts from the originals).
Usage: python tools/cyrillic_fonts.py
"""
