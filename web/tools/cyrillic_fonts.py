def build(name):
    path = FONTS / (name + '.json')
    font = json.loads(path.read_text(encoding='utf8'))
    H = font['height']
    ours = {str(ord(c)) for c in CYR + EXTRA}
    orig = {k: v for k, v in font['glyphs'].items() if k not in ours or int(k) <= font['last']}
    L = lambda ch: to_grid(orig[str(ord(ch))])
    g = {c: L(la) for c, la in TWINS.items()}
    g = DESIGNS[name](L, g)
    missing = set(CYR + EXTRA) - set(g)
    skipped = []
    new = dict(orig)
    for ch in CYR + EXTRA:
        if ch not in g:
            continue
        k = str(ord(ch))
        if k in orig:  # occupied by an original glyph: keep it
            skipped.append(ch)
            continue
        grid = g[ch]
        assert len(grid) == H and len({len(r) for r in grid}) == 1, (name, ch, len(grid))
        new[k] = to_glyph(grid)
    font['glyphs'] = new
    path.write_text(json.dumps(font, separators=(',', ':')), encoding='utf8')
    return font, missing, skipped


# ---- specimen rendering ----

def render(font, lines, scale=3):
    H = font['height']
    gl = font['glyphs']
    width = lambda s: sum(gl[str(ord(c))]['w'] for c in s if str(ord(c)) in gl)
    W = max(width(s) for s in lines) + 8
    img = Image.new('1', (W, (H + 3) * len(lines) + 6), 1)
    px = img.load()
    for i, s in enumerate(lines):
        x, y = 4, 3 + i * (H + 3)
        for c in s:
            g = gl.get(str(ord(c)))
            if not g:
                continue
            for r, row in enumerate(g['rows']):
                for cx in range(g['w']):
                    if row >> (g['w'] - 1 - cx) & 1:
                        px[x + cx, y + r] = 0
            x += g['w']
    return img.resize((img.width * scale, img.height * scale), Image.NEAREST)


